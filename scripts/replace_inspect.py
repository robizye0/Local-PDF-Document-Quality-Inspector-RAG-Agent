with open('backend/main.py', 'r') as f:
    lines = f.readlines()

new_function_lines = [
    '@app.post("/api/v1/inspect", response_model=InspectResponse, status_code=201)\n',
    'async def inspect_document(\n',
    '    file: UploadFile = File(...),\n',
    '    specification: str = "General manufacturing quality standards (ISO 9001 §8.6)",\n',
    '    profile_id: str | None = None,\n',
    '):\n',
    '    """\n',
    '    Upload a PDF and receive a structured QualityInspectionReport.\n',
    '    Uses RAG to retrieve only relevant chunks before sending to the LLM.\n',
    '    Checks below the confidence threshold are enqueued for human review.\n',
    '    """\n',
    '    if not file.filename or not file.filename.lower().endswith(".pdf"):\n',
    '        raise HTTPException(status_code=422, detail="Only PDF files are accepted.")\n',
    '\n',
    '    profile = None\n',
    '    if profile_id:\n',
    '        try:\n',
    '            profile = get_profile(profile_id)\n',
    '        except ValueError as exc:\n',
    '            raise HTTPException(status_code=422, detail=str(exc))\n',
    '\n',
    '    # Start Langfuse trace\n',
    '    trace = trace_inspection_pipeline(file.filename, profile_id)\n',
    '\n',
    '    # Save upload\n',
    '    upload_id = f"{uuid.uuid4().hex[:8]}_{file.filename}"\n',
    '    upload_path = UPLOADS_DIR / upload_id\n',
    '    content = await file.read()\n',
    '    upload_path.write_bytes(content)\n',
    '    logger.info("Uploaded %s (%d bytes)", upload_id, len(content))\n',
    '\n',
    '    # Extract text\n',
    '    try:\n',
    '        doc_text = extract_text(upload_path, max_chars=50_000)\n',
    '    except Exception as exc:\n',
    '        raise HTTPException(status_code=500, detail=f"PDF extraction failed: {exc}")\n',
    '\n',
    '    if len(doc_text.strip()) < 50:\n',
    '        raise HTTPException(status_code=422, detail="Document appears to be empty or image-only (no text layer).")\n',
    '\n',
    '    # Index document in RAG vector store\n',
    '    doc_id = f"doc_{upload_id}"\n',
    '    rag.index_document(doc_id, doc_text, metadata={"filename": file.filename, "profile_id": profile_id or "default"})\n',
    '\n',
    '    # Retrieve relevant chunks using semantic search\n',
    '    retrieved_chunks = rag.retrieve(specification, top_k=5, profile_id=profile_id)\n',
    '    context_text = "\n\n".join([chunk["text"] for chunk in retrieved_chunks])\n',
    '\n',
    '    # Log PDF extraction trace\n',
    '    trace_pdf_extraction(str(upload_path), pages=doc_text.count("\f") + 1, chars_extracted=len(doc_text))\n',
    '\n',
    '    # Run Ollama compliance check with RAG context\n',
    '    start_time = time.perf_counter()\n',
    '    report, error, metrics = ollama.run_compliance_check(context_text, specification, profile)\n',
    '    total_time_ms = (time.perf_counter() - start_time) * 1000\n',
    '\n',
    '    if error:\n',
    '        log_audit("inspection_failed", document=file.filename, profile=profile_id, error=error)\n',
    '        if trace:\n',
    '            trace.update(metadata={"status": "failed", "error": error})\n',
    '        raise HTTPException(status_code=502, detail=f"Ollama inference failed: {error}")\n',
    '\n',
    '    # Human-in-the-Loop routing\n',
    '    review_tickets = []\n',
    '    for check in report.checks:\n',
    '        if check.needs_human_review:\n',
    '            ticket = enqueue_review(check, file.filename, check.review_reason)\n',
    '            review_tickets.append({\n',
    '                "ticket_id": ticket.ticket_id,\n',
    '                "reason": ticket.reason,\n',
    '                "confidence": check.confidence_score,\n',
    '            })\n',
    '\n',
    '    trace_review_routing(len(review_tickets), CONFIDENCE_THRESHOLD)\n',
    '\n',
    '    # Persist report\n',
    '    report_id = f"RPT-{uuid.uuid4().hex[:8].upper()}"\n',
    '    report_path = REPORTS_DIR / f"{report_id}.json"\n',
    '    report_path.write_text(report.model_dump_json(indent=2))\n',
    '\n',
    '    # Export PDF certificate\n',
    '    pdf_path = None\n',
    '    try:\n',
    '        pdf_path = REPORTS_DIR / f"{report_id}.pdf"\n',
    '        export_report_pdf(report, pdf_path)\n',
    '    except Exception as exc:\n',
    '        logger.warning("PDF export failed: %s", exc)\n',
    '\n',
    '    # Audit log\n',
    '    log_audit(\n',
    '        "inspection_completed",\n',
    '        report_id=report_id,\n',
    '        document=file.filename,\n',
    '        profile=profile_id,\n',
    '        total_checks=report.total_checks,\n',
    '        passed=report.passed,\n',
    '        failed=report.failed,\n',
    '        flagged=report.flagged_for_review,\n',
    '        processing_time_ms=round(total_time_ms, 2),\n',
    '        metrics=metrics.model_dump() if metrics else None,\n',
    '        rag_chunks_retrieved=len(retrieved_chunks),\n',
    '    )\n',
    '\n',
    '    if trace:\n',
    '        trace.update(\n',
    '            output={\n',
    '                "report_id": report_id,\n',
    '                "status": "completed",\n',
    '                "total_checks": report.total_checks,\n',
    '                "passed": report.passed,\n',
    '                "failed": report.failed,\n',
    '                "flagged": report.flagged_for_review,\n',
    '                "processing_time_ms": round(total_time_ms, 2),\n',
    '            }\n',
    '        )\n',
    '\n',
    '    return InspectResponse(\n',
    '        report_id=report_id,\n',
    '        document_name=file.filename,\n',
    '        profile_id=profile_id,\n',
    '        summary={\n',
    '            "total_checks": report.total_checks,\n',
    '            "passed": report.passed,\n',
    '            "failed": report.failed,\n',
    '            "flagged_for_review": report.flagged_for_review,\n',
    '            "overall_status": report.overall_status,\n',
    '        },\n',
    '        metrics=metrics.model_dump() if metrics else None,\n',
    '        report_path=str(report_path),\n',
    '        pdf_path=str(pdf_path) if pdf_path else None,\n',
    '        review_tickets=review_tickets,\n',
    '    )\n',
]

start_idx = None
end_idx = None
for i, line in enumerate(lines):
    if 'async def inspect_document(' in line:
        start_idx = i
    if start_idx is not None and i > start_idx and line.strip().startswith('@app.get('):
        end_idx = i
        break

if start_idx is None or end_idx is None:
    print('ERROR: could not find function boundaries')
else:
    new_lines = lines[:start_idx] + new_function_lines + lines[end_idx:]
    with open('backend/main.py', 'w') as f:
        f.writelines(new_lines)
    print(f'Replaced lines {start_idx+1} to {end_idx} with RAG+tracing version')
